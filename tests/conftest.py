def write_journal(path: Path, rows: list[tuple]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="cp932", newline="") as f:
        w = csv.writer(f, quoting=csv.QUOTE_ALL, lineterminator="\r\n")
        w.writerow(COLUMNS)
        for serial, (voucher, line_no, date, kind, (dc, ds), (cc, cs), amount, memo, sub_memo) in enumerate(
            rows, start=1
        ):
            record = dict.fromkeys(COLUMNS, "")
            record.update(
                {
                    "通番": serial, "伝票番号": voucher, "行番号": line_no, "伝票日付": date,
                    "取引区分コード": {"売上取引": 1, "経費取引": 3, "財務取引": 5, "決算取引": 9}[kind],
                    "取引区分名称": kind,
                    "借方科目コード": dc, "借方科目名称": SOFT_NAMES[dc], "借方補助コード": ds,
                    "借方補助科目名称": SUB_NAMES.get((dc, ds), ""), "借方金額": amount, "借方消費税": 0,
                    "貸方科目コード": cc, "貸方科目名称": SOFT_NAMES[cc], "貸方補助コード": cs,
                    "貸方補助科目名称": SUB_NAMES.get((cc, cs), ""), "貸方金額": amount, "貸方消費税": 0,
                    "取引摘要": memo, "補助摘要": sub_memo,
                }
            )
            w.writerow([record[c] for c in COLUMNS])


